"""Repository boundary: sessions are short-lived and never shared between tools."""

from typing import Protocol
from app.schemas import CampaignBrief


class DraftRepository(Protocol):
    def claim_campaign(self, brief: CampaignBrief) -> tuple[str, dict | None]: ...
    def save_draft(self, tenant_id: str, campaign_id: str, platform: str, text: str, media_suggestion: str, qa_issues: list[dict]) -> dict: ...
    def discard_attempt(self, tenant_id: str, campaign_id: str) -> None: ...
    def complete_campaign(self, tenant_id: str, campaign_id: str, result: dict) -> None: ...
    def fail_campaign(self, tenant_id: str, campaign_id: str, error_code: str) -> None: ...
    def get_campaign(self, tenant_id: str, campaign_id: str) -> dict: ...
    def get_draft(self, tenant_id: str, draft_id: str) -> dict: ...
